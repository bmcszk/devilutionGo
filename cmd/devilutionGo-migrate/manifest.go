package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/csv"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/bmcszk/devilutionGo/internal/assets"
)

const (
	// manifestName is the single YAML asset list ADR-013 fixes for flat file
	// lists (no TSV fork).
	manifestName = "manifest.yaml"
	// manifestTool and manifestVersion identify the writer, so a reader can
	// refuse a list it does not understand.
	manifestTool    = "devilutionGo-migrate"
	manifestVersion = 1
)

// Asset families: which decoder produced a file, and therefore what a loader may
// assume about it.
const (
	familyTable   = "table"
	familySprite  = "sprite"
	familyFont    = "font"
	familyPalette = "palette"
	familyTRN     = "trn"
	familyRaw     = "raw"
)

// fileEntry is one produced file: where it landed, which archive record it came
// from, how it decodes, and its hash. The same entry is written to manifest.yaml
// and stored in the journal, so a resumed run rebuilds the list without decoding
// again.
type fileEntry struct {
	Path    string       `yaml:"path"             json:"path"`
	Archive string       `yaml:"archive"          json:"archive"`
	Source  string       `yaml:"source"           json:"source"`
	Family  string       `yaml:"family"           json:"family"`
	Format  string       `yaml:"format"           json:"format"`
	Frames  *frameLayout `yaml:"frames,omitempty" json:"frames,omitempty"`
	Rows    int          `yaml:"rows,omitempty"   json:"rows,omitempty"`
	Bytes   int          `yaml:"bytes"            json:"bytes"`
	SHA256  string       `yaml:"sha256"           json:"sha256"`

	// Conversion names the legacy container inputs when Format is clx because the
	// record was converted rather than extracted (ADR-019).
	Conversion *conversionRecord `yaml:"conversion,omitempty" json:"conversion,omitempty"`

	// payload is the decoded file content of a freshly extracted record; a
	// journal-resumed entry carries none because its file is already on disk.
	payload []byte
}

// frameLayout is the sprite frame geometry, when the format carries it.
type frameLayout struct {
	Count  int   `yaml:"count"            json:"count"`
	Width  int   `yaml:"width,omitempty"  json:"width,omitempty"`
	Height int   `yaml:"height,omitempty" json:"height,omitempty"`
	Groups []int `yaml:"groups,omitempty" json:"groups,omitempty"`
}

// archiveRef is one source archive as the manifest records it.
type archiveRef struct {
	Path     string `yaml:"path"          json:"path"`
	Bytes    int64  `yaml:"bytes"         json:"bytes"`
	Modified int64  `yaml:"modified_unix" json:"modified_unix"`
	Files    int    `yaml:"files"         json:"files"`
}

// manifestSummary is the idempotency check: unchanged inputs give an unchanged
// hash over every produced path and its content hash.
type manifestSummary struct {
	Files  int    `yaml:"files"`
	Bytes  int    `yaml:"bytes"`
	SHA256 string `yaml:"sha256"`
}

// manifest is the written asset list.
type manifest struct {
	Tool     string          `yaml:"tool"`
	Version  int             `yaml:"version"`
	Archives []archiveRef    `yaml:"archives"`
	Files    []fileEntry     `yaml:"files"`
	Summary  manifestSummary `yaml:"summary"`
}

// buildManifest assembles the asset list from the archives this run covered and
// every file they produced.
func buildManifest(archives []string, state *journal, entries []fileEntry) manifest {
	refs := make([]archiveRef, 0, len(archives))

	for _, archive := range archives {
		recorded := state.Archives[archive]
		refs = append(refs, archiveRef{
			Path:     archive,
			Bytes:    recorded.Bytes,
			Modified: recorded.Modified,
			Files:    len(recorded.Files),
		})
	}

	listed := manifest{
		Tool:     manifestTool,
		Version:  manifestVersion,
		Archives: refs,
		Files:    entries,
		Summary:  summarize(entries),
	}

	return listed
}

// summarize hashes the produced file set: path and content hash, sorted by path,
// so the summary depends on the data and not on walk order.
func summarize(entries []fileEntry) manifestSummary {
	lines := make([]string, 0, len(entries))
	total := 0

	for _, entry := range entries {
		lines = append(lines, entry.Path+"\t"+entry.SHA256)
		total += entry.Bytes
	}

	slices.Sort(lines)

	digest := sha256.Sum256([]byte(strings.Join(lines, "\n") + "\n"))

	return manifestSummary{Files: len(entries), Bytes: total, SHA256: hex.EncodeToString(digest[:])}
}

// writeManifest writes the YAML asset list into the assets dir.
func writeManifest(out string, listed manifest) error {
	var buffer bytes.Buffer

	_, _ = buffer.WriteString("# Generated by devilutionGo-migrate assets; do not edit (ADR-013).\n")

	encoder := yaml.NewEncoder(&buffer)
	encoder.SetIndent(2)

	if err := encoder.Encode(listed); err != nil {
		return fmt.Errorf("encode manifest: %w", err)
	}

	if err := encoder.Close(); err != nil {
		return fmt.Errorf("encode manifest: %w", err)
	}

	if err := writeOutput(filepath.Join(out, manifestName), buffer.Bytes()); err != nil {
		return fmt.Errorf("write manifest: %w", err)
	}

	return nil
}

// writeOutput writes one produced file, creating its directory.
func writeOutput(path string, content []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("create output dir: %w", err)
	}

	if err := os.WriteFile(path, content, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}

	return nil
}

// tableCSV renders a parsed table as the CSV file ADR-013 fixes for game data,
// values verbatim so the port keeps the original numbers.
func tableCSV(table *assets.Table) ([]byte, error) {
	var buffer bytes.Buffer

	writer := csv.NewWriter(&buffer)

	if err := writer.Write(table.Header); err != nil {
		return nil, fmt.Errorf("write header: %w", err)
	}

	for _, row := range table.Rows {
		if err := writer.Write(row.Fields); err != nil {
			return nil, fmt.Errorf("write row: %w", err)
		}
	}

	writer.Flush()

	if err := writer.Error(); err != nil {
		return nil, fmt.Errorf("write csv: %w", err)
	}

	return buffer.Bytes(), nil
}

// digest is the sha256 the manifest lists for one file.
func digest(content []byte) string {
	sum := sha256.Sum256(content)

	return hex.EncodeToString(sum[:])
}
