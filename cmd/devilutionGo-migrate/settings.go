const (
	// settingsIniName is the settings file name upstream reads
	// (Source/utils/paths.cpp PrefPath).
	settingsIniName = "diablo.ini"
	// portableMarkerName is the portable-install marker per ADR-004
	// (docs/adrs/adr-004.md, "portable.ini supported"); upstream instead
	// treats a writeable diablo.ini in the working dir as the marker
	// (Source/utils/paths.cpp PrefPath).
	portableMarkerName = "portable.ini"
	// settingsOrg and settingsApp are the SDL pref path components
	// (Source/utils/paths.cpp PrefPath: SDL_GetPrefPath(org, app)).
	settingsOrg = "diasurgical"
	settingsApp = "devilution"
	// settingsViewPrefix names one flat YAML view per INI section family;
	// the ini stays canonical, views are engine tooling input (ADR-013).
	settingsViewPrefix = "settings_"
	// settingsViewHeader opens every view file.
	settingsViewHeader = "# Generated by devilutionGo-migrate settings; do not edit; " +
		"the ini stays canonical (ADR-004, ADR-013).\n"
)

// settingsUsage is the flag help the ErrHelp path prints.
const settingsUsage = `settings flags:

  --ini      diablo.ini to check and carry over (default: the engine settings path)
  --out      engine settings dir to write into (default: the engine settings path)
  --dry-run  report the plan without writing files
`

// settingsConfig is one `settings` invocation.
type settingsConfig struct {
	ini    string
	out    string
	dryRun bool
}

// iniDocumentScan is the document outline: the section names in order, each
// section's key names in order, and the section the scan is under.
type iniDocumentScan struct {
	current string
	names   []string
	keys    map[string][]string
}

// settingsSection is one INI section family the views and the report cover.
type settingsSection struct {
	name string
	keys []settingsKey
}

// settingsKey is one key=value occurrence as the view carries it: the value
// verbatim plus the INI coordinates for traceability.
type settingsKey struct {
	Key    string `yaml:"key"`
	Value  string `yaml:"value"`
	Source string `yaml:"source"`
}

// settingsView is one flat family view. YAML is a view; the ini stays
// canonical (ADR-013).
type settingsView struct {
	Tool    string        `yaml:"tool"`
	Version int           `yaml:"version"`
	Section string        `yaml:"section"`
	Keys    []settingsKey `yaml:"keys"`
}

// settingsReport is what one settings run did and what it could not fix.
type settingsReport struct {
	violations []string
	views      int
	dryRun     bool
}

// write prints the run report: each violation the check cannot fix, then the
// mode line (assets report shape).
func (r settingsReport) write(stdout io.Writer) {
	for _, violation := range r.violations {
		_, _ = fmt.Fprintf(stdout, "devilutionGo-migrate: settings: %s\n", violation)
	}

	mode := "wrote"
	if r.dryRun {
		mode = "planned"
	}

	_, _ = fmt.Fprintf(stdout, "%s diablo.ini carry-over and %d registry view(s), %d unfixable violation(s)\n",
		mode, r.views, len(r.violations))
}

// runSettingsCommand checks and carries diablo.ini over into the engine
// settings dir and reports the exit code (ADR-014, ADR-004).
func runSettingsCommand(args []string, stdout, stderr io.Writer) int {
	cfg, err := parseSettingsFlags(args, stderr)
	if err != nil {
		if errors.Is(err, flag.ErrHelp) {
			_, _ = fmt.Fprint(stderr, settingsUsage)

			return exitOK
		}

		return exitUsage
	}

	report, err := migrateSettings(cfg, stderr)
	if err != nil {
		_, _ = fmt.Fprintf(stderr, "devilutionGo-migrate: settings: %v\n", err)

		return exitFailure
	}

	report.write(stdout)

	return exitOK
}

// parseSettingsFlags reads the settings flags. The flag package writes its own
// diagnostics to stderr, so an error needs no extra message.
func parseSettingsFlags(args []string, stderr io.Writer) (settingsConfig, error) {
	flags := flag.NewFlagSet("devilutionGo-migrate settings", flag.ContinueOnError)
	flags.SetOutput(stderr)

	ini := flags.String("ini", "", "diablo.ini to check and carry over (default: the engine settings path)")
	out := flags.String("out", "", "engine settings dir to write into (default: the engine settings path)")
	dryRun := flags.Bool("dry-run", false, "report the plan without writing files")

	if err := flags.Parse(args); err != nil {
		return settingsConfig{}, fmt.Errorf("parse flags: %w", err)
	}

	return settingsConfig{ini: *ini, out: *out, dryRun: *dryRun}, nil
}

// migrateSettings checks diablo.ini, carries it byte-identical into the
// engine settings dir (ADR-004), and writes the flat YAML registry views
// engine tooling reads (ADR-013). Violations never block the carry; an ini
// the parser rejects fails the run before anything is written. On success
// it logs the resolved ini on stderr.
func migrateSettings(cfg settingsConfig, stderr io.Writer) (settingsReport, error) {
	iniPath, out, err := resolveSettingsPaths(cfg)
	if err != nil {
		return settingsReport{}, err
	}

	_, _ = fmt.Fprintf(stderr, "devilutionGo-migrate: settings: --ini %s\n", iniPath)

	source, err := readDiabloIni(iniPath)
	if err != nil {
		return settingsReport{}, err
	}

	parsed, err := engine.ParseIni(source)
	if err != nil {
		return settingsReport{}, fmt.Errorf("parse %s: %w", iniPath, err)
	}

	families := settingsFamilies(parsed, source)

	report := settingsReport{violations: checkIni(families), views: len(families), dryRun: cfg.dryRun}

	if cfg.dryRun {
		return report, nil
	}

	if err := carrySettingsIni(out, source); err != nil {
		return settingsReport{}, err
	}

	if err := writeSettingsViews(out, families); err != nil {
		return settingsReport{}, err
	}

	return report, nil
}

// resolveSettingsPaths resolves the ini and the destination dir: explicit
// flags win; a default on either side is the engine settings path (ADR-004).
func resolveSettingsPaths(cfg settingsConfig) (iniPath, out string, err error) {
	iniPath, out = cfg.ini, cfg.out

	if iniPath != "" && out != "" {
		return iniPath, out, nil
	}

	dir, dirErr := resolveSettingsDir()
	if dirErr != nil {
		return "", "", dirErr
	}

	if out == "" {
		out = dir
	}

	if iniPath == "" {
		iniPath = filepath.Join(dir, settingsIniName)
	}

	return iniPath, out, nil
}

// resolveSettingsDir resolves the directory the engine reads diablo.ini from
// (ADR-004): the working dir when it holds portable.ini (the ADR-004 marker
// law; upstream instead falls back to the base path when a writeable
// diablo.ini sits in the working dir, paths.cpp PrefPath), else the SDL pref
// dir SDL_GetPrefPath("diasurgical", "devilution") (paths.cpp PrefPath).
func resolveSettingsDir() (string, error) {
	cwd, err := os.Getwd()
	if err != nil {
		return "", fmt.Errorf("working dir: %w", err)
	}

	if _, err := os.Stat(filepath.Join(cwd, portableMarkerName)); err == nil {
		return cwd, nil
	}

	home, err := os.UserHomeDir()
	if err != nil {
		return "", fmt.Errorf("home dir: %w", err)
	}

	// POSIX-only pref layout: the Linux SDL_GetPrefPath shape; macOS and
	// Windows resolve differently upstream (paths.cpp PrefPath) — per-platform
	// resolution is a recorded deviation decision (review round 1, F2).
	base := filepath.Join(home, ".local", "share")
	if xdg := os.Getenv("XDG_DATA_HOME"); xdg != "" {
		base = xdg
	}

	return filepath.Join(base, settingsOrg, settingsApp), nil
}

// readDiabloIni reads the configured ini bytes.
func readDiabloIni(path string) ([]byte, error) {
	source, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}

	return source, nil
}

// carrySettingsIni writes the ini into the engine settings dir and verifies
// the copy is byte-identical to the source. Violations are reported, never
// rewritten into the copy.
func carrySettingsIni(out string, source []byte) error {
	if err := os.MkdirAll(out, 0o755); err != nil {
		return fmt.Errorf("create settings dir: %w", err)
	}

	destination := filepath.Join(out, settingsIniName)

	if err := os.WriteFile(destination, source, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", destination, err)
	}

	carried, err := os.ReadFile(destination)
	if err != nil {
		return fmt.Errorf("verify %s: %w", destination, err)
	}

	if !bytes.Equal(carried, source) {
		return fmt.Errorf("carried ini %s is not byte-identical to the source", destination)
	}

	return nil
}

// settingsFamilies groups the document into one family per INI section in
// document order; values resolve through the engine reader so views carry
// what the engine reads, verbatim (Source/utils/ini.cpp:215).
func settingsFamilies(in *engine.Ini, source []byte) []settingsSection {
	outline := scanIniDocument(source)

	families := make([]settingsSection, 0, len(outline.names))

	for _, name := range outline.names {
		families = append(families, settingsSection{name: name, keys: settingsKeys(in, name, outline.keys[name])})
	}

	return families
}

// scanIniDocument outlines the document from the same grammar the engine
// parser accepts (Source/utils/ini.cpp:171-205); repeated sections and keys
// collapse to one entry each because the engine reader merges them
// (ini.cpp:171-194). It runs only on documents ParseIni already accepted.
func scanIniDocument(source []byte) iniDocumentScan {
	scan := iniDocumentScan{keys: map[string][]string{}}

	for _, trimmed := range iniScanLines(source) {
		scan.scanLine(trimmed)
	}

	return scan
}

// scanLine classifies one remaining line as a section header or a key line.
func (s *iniDocumentScan) scanLine(trimmed string) {
	if strings.HasPrefix(trimmed, "[") {
		s.current = s.addSection(trimmed)

		return
	}

	s.addKey(s.current, trimmed)
}

// iniScanLines splits the document like the engine line walker, skips the
// UTF-8 BOM like the parser (ini.cpp:63), and drops blank and comment
// lines; only section headers and key lines remain.
func iniScanLines(source []byte) []string {
	lines := make([]string, 0)

	text := strings.TrimPrefix(string(source), "\xef\xbb\xbf") // SkipUtf8Bom (ini.cpp:63)

	for _, line := range strings.Split(strings.ReplaceAll(text, "\r\n", "\n"), "\n") {
		trimmed := strings.TrimLeft(line, " \t")
		if trimmed == "" || strings.HasPrefix(trimmed, ";") {
			continue
		}

		lines = append(lines, trimmed)
	}

	return lines
}

// addSection records a new section family and returns its name; malformed
// headers cannot occur post-ParseIni and are skipped.
func (s *iniDocumentScan) addSection(trimmed string) string {
	end := strings.IndexByte(trimmed, ']')
	if end == -1 {
		return ""
	}

	name := trimmed[1:end]
	if name == "" || slices.Contains(s.names, name) {
		return name
	}

	s.names = append(s.names, name)
	s.keys[name] = []string{}

	return name
}

// addKey records one key name in document order.
func (s *iniDocumentScan) addKey(section, trimmed string) {
	if section == "" {
		return
	}

	eq := strings.IndexByte(trimmed, '=')
	if eq == -1 {
		return
	}

	key := strings.Trim(trimmed[:eq], " \t")
	if key == "" || slices.Contains(s.keys[section], key) {
		return
	}

	s.keys[section] = append(s.keys[section], key)
}

// settingsKeys resolves every value of the section's keys through the engine
// reader, one view entry per occurrence.
func settingsKeys(in *engine.Ini, section string, keyNames []string) []settingsKey {
	keys := make([]settingsKey, 0, len(keyNames))

	for _, key := range keyNames {
		for _, value := range in.Get(section, key) {
			keys = append(keys, settingsKey{Key: key, Value: value.Value, Source: section + "." + key})
		}
	}

	return keys
}

// checkIni lists what the migration cannot fix: typed values outside the
// upstream bounds, and keys no typed option reads. The ini is never
// rewritten; the operator decides.
func checkIni(families []settingsSection) []string {
	violations := make([]string, 0)

	for _, family := range families {
		for _, key := range family.keys {
			if violation := checkSettingsValue(key); violation != "" {
				violations = append(violations, violation)
			}
		}
	}

	return violations
}

// checkSettingsValue names the value the engine cannot read typed, or ""
// when it is in bounds. Only the typed seams the engine exposes are checked;
// the full upstream option registry is not ported yet.
func checkSettingsValue(key settingsKey) string {
	switch key.Source {
	case "Game.Speed":
		return checkTickRate(key)
	case "Audio.Sample Rate":
		return checkSampleRate(key)
	}

	return key.Source + " is not carried into any typed option"
}

// checkTickRate names a speed outside the sgGameInitInfo bounds
// (Source/gamemenu.cpp:276-277).
func checkTickRate(key settingsKey) string {
	value, err := strconv.Atoi(key.Value)
	if err != nil {
		return notANumber(key)
	}

	if value < engine.TickRateMin || value > engine.TickRateMax {
		return fmt.Sprintf("%s=%d is outside the %d..%d range", key.Source, value, engine.TickRateMin, engine.TickRateMax)
	}

	return ""
}

// checkSampleRate names a rate outside the upstream entries
// (Source/options.cpp:520).
func checkSampleRate(key settingsKey) string {
	value, err := strconv.Atoi(key.Value)
	if err != nil {
		return notANumber(key)
	}

	if !engine.ValidAudioSampleRate(value) {
		return fmt.Sprintf("%s=%d is not one of the supported rates", key.Source, value)
	}

	return ""
}

// notANumber names a value the typed reader would reject.
func notANumber(key settingsKey) string {
	return key.Source + "=" + key.Value + " is not a whole number"
}

// writeSettingsViews writes one flat YAML view per section family under out.
func writeSettingsViews(out string, families []settingsSection) error {
	if err := os.MkdirAll(out, 0o755); err != nil {
		return fmt.Errorf("create settings dir: %w", err)
	}

	for _, family := range families {
		view, err := renderSettingsView(family)
		if err != nil {
			return err
		}

		name := settingsViewPrefix + strings.ToLower(family.name) + ".yaml"

		if err := writeOutput(filepath.Join(out, name), view); err != nil {
			return err
		}
	}

	return nil
}

// renderSettingsView renders one family's flat YAML with the manifest
// writer's shape: header comment, 2-space indent.
func renderSettingsView(family settingsSection) ([]byte, error) {
	var buffer bytes.Buffer

	_, _ = buffer.WriteString(settingsViewHeader)

	listed := settingsView{Tool: manifestTool, Version: manifestVersion, Section: family.name, Keys: family.keys}

	encoder := yaml.NewEncoder(&buffer)
	encoder.SetIndent(2)

	if err := encoder.Encode(listed); err != nil {
		return nil, fmt.Errorf("encode %s view: %w", family.name, err)
	}

	if err := encoder.Close(); err != nil {
		return nil, fmt.Errorf("encode %s view: %w", family.name, err)
	}

	return buffer.Bytes(), nil
}
