#!/usr/bin/env python3
"""Generate internal/diablo/gamedata/audio/sfx_ids.go from the committed corpus.

The id column of effects.tsv is the SfxID vocabulary (sound_effect_enums.h);
effects.cpp:141-158 LoadEffectsData reads the same column into sgSFX. The
committed hf-effects.tsv is a superset of effects.tsv, so it spans every id.

Usage: python3 scripts/gen_sfx_ids.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "internal/testdata/gamedata/audio/hf-effects.tsv")
OUT = os.path.join(ROOT, "internal/diablo/gamedata/audio/sfx_ids.go")

HEADER = """// Code generated by scripts/gen_sfx_ids.py from internal/testdata/gamedata/audio/hf-effects.tsv (devilutionX ca91d778). DO NOT EDIT.
//
// The id column of effects.tsv is the SfxID vocabulary (sound_effect_enums.h);
// effects.cpp:141-158 LoadEffectsData reads the same column into sgSFX. The
// Hellfire table is a superset of the base table, so it spans base ids too.
package audio

// SfxID names one sound effect: the id column of effects.tsv.
type SfxID string

// The effect ids, in Hellfire effects.tsv row order.
const (
"""


def main() -> None:
    with open(SRC, encoding="utf-8") as table:
        rows = table.read().splitlines()[1:]

    seen, constants = set(), []
    for row in rows:
        sfx_id = row.split("\t")[0].strip()
        if not sfx_id or sfx_id in seen:
            continue
        seen.add(sfx_id)
        constants.append('\tSfx%s SfxID = "%s"' % (sfx_id, sfx_id))

    with open(OUT, "w", encoding="utf-8") as out:
        out.write(HEADER + "\n".join(constants) + "\n)\n")


if __name__ == "__main__":
    main()
